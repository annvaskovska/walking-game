/** Signed difference between two angles in degrees, folded into [-180, 180). */
const angleDiff = (a: number, b: number): number => ((a - b + 540) % 360) - 180;

describe('declinationDeg against the official WMM2025 test values', () => {
  it('matches every published declination to within 0.01°', () => {
    let worst = 0;
    for (const [year, alt, lat, lon, d] of OFFICIAL) {
      const err = Math.abs(angleDiff(declinationDeg(lat, lon, year, alt), d));
      worst = Math.max(worst, err);
    }
    expect(worst).toBeLessThan(0.01);
  });

  it('matches the direction of the published X and Y components far more tightly', () => {
    let worst = 0;
    for (const [year, alt, lat, lon, , x, y] of OFFICIAL) {
      const exact = Math.atan2(y, x) * (180 / Math.PI);
      worst = Math.max(worst, Math.abs(angleDiff(declinationDeg(lat, lon, year, alt), exact)));
    }
    expect(worst).toBeLessThan(1e-4);
  });
});

describe('declinationDeg in the demo city', () => {
  it('is a little east in Amsterdam', () => {
    const d = declinationDeg(52.37, 4.88, 2026.9);
    expect(d).toBeGreaterThan(1);
    expect(d).toBeLessThan(4);
  });
  it('defaults to ground level', () => {
    expect(declinationDeg(52.37, 4.88, 2026.9)).toBe(declinationDeg(52.37, 4.88, 2026.9, 0));
  });
});

describe('declinationDeg outside the model years', () => {
  it('keeps the 2030 value after the model expires', () => {
    expect(declinationDeg(52.37, 4.88, 2034.2)).toBe(declinationDeg(52.37, 4.88, 2030));
  });
  it('uses the 2025 value before the epoch', () => {
    expect(declinationDeg(52.37, 4.88, 2019)).toBe(declinationDeg(52.37, 4.88, 2025));
  });
  it('stays finite at the poles and the antimeridian', () => {
    for (const [lat, lon] of [[90, 0], [-90, 0], [0, 180], [0, -180]]) {
      expect(Number.isFinite(declinationDeg(lat, lon, 2027))).toBe(true);
    }
  });
});

describe('decimalYear', () => {
  it('starts each year at a whole number', () => {
    expect(decimalYear(new Date(Date.UTC(2026, 0, 1)))).toBe(2026);
  });
  it('is half way through in early July', () => {
    expect(decimalYear(new Date(Date.UTC(2026, 6, 2, 12)))).toBeCloseTo(2026.5, 6);
  });
  it('counts the extra day of a leap year', () => {
    expect(decimalYear(new Date(Date.UTC(2028, 6, 2)))).toBeCloseTo(2028.5, 6);
  });
});
